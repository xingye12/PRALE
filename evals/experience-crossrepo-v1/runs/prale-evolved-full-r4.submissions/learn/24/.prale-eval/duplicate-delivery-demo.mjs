#!/usr/bin/env node
/**
 * Executable demo (task learn/24, repository wattclaw, mode contract):
 * prove duplicate delivery is harmless for session synchronization.
 *
 * How it works
 * ------------
 * `server/core/session-sync.js` has exactly one external dependency for the
 * sync path: `../user-manager.js` (getAllGatewayAgentIds, getUserOwnedAgentIds,
 * upsertSyncedUserSession). That module pulls in better-sqlite3, which is not
 * installed in this sandbox (no node_modules). So this demo:
 *
 *   1. reads the real `server/core/session-sync.js`,
 *   2. rewrites ONLY the user-manager import specifier so it resolves to an
 *      in-memory stub placed next to the harness copy,
 *   3. imports and exercises the real session-sync code (scheduleUserSessionSync,
 *      syncUserSessionsFromGateway, normalizeGatewaySessionForSync, ...).
 *
 * The stub's `upsertSyncedUserSession` is a line-faithful transcription of the
 * comparison / write logic in `server/user-manager.js:614-688`: rows are keyed
 * by `session_key`, every persisted field is compared before writing, and
 * `{ changed: false, action: 'unchanged' }` is returned (no UPDATE, no counter
 * movement) whenever the incoming payload matches the stored row.
 *
 * Only Node builtins are used. Run: node .prale-eval/duplicate-delivery-demo.mjs
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const workspaceRoot = resolve(here, '..')
const harnessDir = join(here, '.harness')
const targetSource = join(workspaceRoot, 'server', 'core', 'session-sync.js')
const IMPORT_SPECIFIER = "from '../user-manager.js'"

const failures = []
const results = []

function check(name, condition, detail) {
  results.push({ scenario: name, ok: Boolean(condition), detail })
  if (!condition) failures.push(`${name}: ${JSON.stringify(detail)}`)
}

// ---------------------------------------------------------------------------
// Harness generation
// ---------------------------------------------------------------------------
const stubSource = `// GENERATED by .prale-eval/duplicate-delivery-demo.mjs — in-memory stand-in for
// server/user-manager.js. Keyed by session_key; comparison logic transcribed
// from server/user-manager.js:614-688 (upsertSyncedUserSession).
const state = {
  ownedAgents: new Map(),
  allAgents: [],
  rows: new Map(),          // sessionKey -> stored row
  upsertCalls: 0,
  insertWrites: 0,
  updateWrites: 0,
  lastResults: [],
}

export function __configure({ ownedAgents = {}, allAgents = [] } = {}) {
  state.ownedAgents = new Map(Object.entries(ownedAgents))
  state.allAgents = [...allAgents]
}

export function __reset() {
  state.rows = new Map()
  state.upsertCalls = 0
  state.insertWrites = 0
  state.updateWrites = 0
  state.lastResults = []
}

export function __stats() {
  return {
    upsertCalls: state.upsertCalls,
    insertWrites: state.insertWrites,
    updateWrites: state.updateWrites,
    lastResults: state.lastResults.map(r => ({ ...r })),
  }
}

export function __rows() {
  return JSON.parse(JSON.stringify([...state.rows.entries()]))
}

export function getAllGatewayAgentIds() {
  return [...state.allAgents]
}

export function getUserOwnedAgentIds(userId) {
  return [...(state.ownedAgents.get(userId) || [])]
}

function normalizeSessionUpdatedAt(value, fallback = null) {
  if (typeof value === 'number' && Number.isFinite(value) && value > 0) {
    return value > 1e12 ? Math.floor(value) : Math.floor(value * 1000)
  }
  if (typeof value === 'string' && value.trim()) {
    const numeric = Number(value)
    if (Number.isFinite(numeric) && numeric > 0) {
      return numeric > 1e12 ? Math.floor(numeric) : Math.floor(numeric * 1000)
    }
    const parsed = Date.parse(value)
    if (Number.isFinite(parsed)) return parsed
  }
  return fallback
}

function readNormalizedLabel(label) {
  return typeof label === 'string' && label.trim() ? label.trim() : null
}

function readNormalizedDisplayTitle(title, peer) {
  return readNormalizedLabel(title) || readNormalizedLabel(peer)
}

export function upsertSyncedUserSession({ userId, sessionKey, agentId, channel, peer, label, lastActivity }) {
  if (!userId || !sessionKey) return { changed: false, action: 'skipped' }
  state.upsertCalls += 1

  const lastMessageAt = normalizeSessionUpdatedAt(lastActivity, null)
  const incomingDisplayTitle = readNormalizedDisplayTitle(label, peer)
  const existing = state.rows.get(sessionKey) || null

  if (!existing) {
    state.rows.set(sessionKey, {
      user_id: userId,
      session_key: sessionKey,
      agent_id: agentId || null,
      label: label || null,
      channel: channel || null,
      peer_id: peer || null,
      display_title: incomingDisplayTitle,
      last_message_at: lastMessageAt,
    })
    state.insertWrites += 1
    const result = { changed: true, action: 'inserted' }
    state.lastResults.push(result)
    return result
  }

  const cleanExistingDisplayTitle = readNormalizedDisplayTitle(existing.display_title, existing.peer_id)
  const cleanExistingLabel = readNormalizedLabel(existing.label)
  const cleanIncomingLabel = readNormalizedLabel(label)
  const nextAgentId = agentId || existing.agent_id || null
  const nextChannel = channel || existing.channel || null
  const nextPeerId = peer || existing.peer_id || null
  const nextLabel = cleanExistingLabel || cleanIncomingLabel || null
  const nextDisplayTitle = cleanExistingDisplayTitle || incomingDisplayTitle || null
  const currentLastMessageAt = Number(existing.last_message_at) || 0
  const nextLastMessageAt = lastMessageAt == null
    ? existing.last_message_at || null
    : Math.max(currentLastMessageAt, lastMessageAt)

  const changed =
    nextAgentId !== (existing.agent_id || null) ||
    nextChannel !== (existing.channel || null) ||
    nextPeerId !== (existing.peer_id || null) ||
    nextLabel !== (existing.label || null) ||
    nextDisplayTitle !== (existing.display_title || null) ||
    nextLastMessageAt !== (existing.last_message_at || null)

  if (!changed) {
    const result = { changed: false, action: 'unchanged' }
    state.lastResults.push(result)
    return result
  }

  state.rows.set(sessionKey, {
    ...existing,
    agent_id: nextAgentId,
    channel: nextChannel,
    peer_id: nextPeerId,
    label: nextLabel,
    display_title: nextDisplayTitle,
    last_message_at: nextLastMessageAt,
  })
  state.updateWrites += 1
  const result = { changed: true, action: 'updated' }
  state.lastResults.push(result)
  return result
}
`

const source = readFileSync(targetSource, 'utf8')
if (!source.includes(IMPORT_SPECIFIER)) {
  console.error(`FATAL: ${targetSource} no longer imports from '../user-manager.js'; demo harness needs updating`)
  process.exit(2)
}

rmSync(harnessDir, { recursive: true, force: true })
mkdirSync(harnessDir, { recursive: true })
writeFileSync(join(harnessDir, 'user-manager-stub.mjs'), stubSource)
writeFileSync(
  join(harnessDir, 'session-sync.mjs'),
  source.replace(IMPORT_SPECIFIER, "from './user-manager-stub.mjs'"),
)

const sync = await import(pathToFileURL(join(harnessDir, 'session-sync.mjs')).href)
const stub = await import(pathToFileURL(join(harnessDir, 'user-manager-stub.mjs')).href)

// ---------------------------------------------------------------------------
// Scenarios
// ---------------------------------------------------------------------------
const SESSION_A = 'agent:agent-a:feishu:dm:ou_xxx'
const LAST_ACTIVITY = '2026-06-05T12:00:00.000Z'
const LAST_ACTIVITY_MS = Date.parse(LAST_ACTIVITY)

function delivery(overrides = {}) {
  return { key: SESSION_A, agentId: 'agent-a', channel: 'feishu', peer: 'ou_xxx', label: 'Feishu chat', updatedAt: LAST_ACTIVITY, ...overrides }
}

function newGateway(sessionsPerCall) {
  const calls = []
  const gatewayRpc = async (method, params) => {
    calls.push({ method, params })
    const payload = typeof sessionsPerCall === 'function' ? sessionsPerCall(params) : sessionsPerCall
    return { ok: true, payload: { sessions: payload } }
  }
  gatewayRpc.calls = calls
  return gatewayRpc
}

function freshWorld() {
  stub.__configure({ ownedAgents: { 'user-1': ['agent-a'] }, allAgents: ['agent-a'] })
  stub.__reset()
  sync.resetSessionSyncStateForTests()
}

// S1 — the same gateway delivery applied twice: first delivery persists one row,
// the replayed delivery is a no-op write (comparison guard in upsertSyncedUserSession).
{
  freshWorld()
  const gatewayRpc = newGateway([delivery()])

  const first = await sync.syncUserSessionsFromGateway({ userId: 'user-1', role: 'user', gatewayRpc })
  const rowsAfterFirst = stub.__rows()
  const writesAfterFirst = stub.__stats()

  const second = await sync.syncUserSessionsFromGateway({ userId: 'user-1', role: 'user', gatewayRpc })
  const rowsAfterSecond = stub.__rows()
  const writesAfterSecond = stub.__stats()

  check('S1.first-delivery-inserts-once', first.changed === 1 && first.inserted === 1 && first.updated === 0 && first.scanned === 1,
    { first })
  check('S1.replayed-delivery-reports-no-change', second.changed === 0 && second.inserted === 0 && second.updated === 0 && second.scanned === 1,
    { second })
  check('S1.replayed-delivery-writes-nothing', writesAfterFirst.insertWrites === 1 && writesAfterFirst.updateWrites === 0 &&
    writesAfterSecond.insertWrites === 1 && writesAfterSecond.updateWrites === 0,
    { writesAfterFirst, writesAfterSecond })
  check('S1.persisted-row-byte-identical-after-replay', JSON.stringify(rowsAfterFirst) === JSON.stringify(rowsAfterSecond) &&
    rowsAfterSecond.length === 1 && rowsAfterSecond[0][1].last_message_at === LAST_ACTIVITY_MS,
    { rowsAfterSecond })
  check('S1.duplicate-delivery-scan-is-still-bounded', gatewayRpc.calls.length === 2 &&
    gatewayRpc.calls.every(c => c.method === 'sessions.list'), { calls: gatewayRpc.calls.length })
}

// S2 — two concurrent duplicate triggers for the same user collapse onto one
// in-flight sync (inFlightByUserId), so the second delivery performs no work.
{
  freshWorld()
  let gatewayInvocations = 0
  const gatewayRpc = async () => {
    gatewayInvocations += 1
    await new Promise(resolve => setTimeout(resolve, 10))
    return { ok: true, payload: { sessions: [delivery()] } }
  }

  const p1 = sync.scheduleUserSessionSync({ userId: 'user-1', role: 'user', gatewayRpc, cooldownMs: 0 })
  const p2 = sync.scheduleUserSessionSync({ userId: 'user-1', role: 'user', gatewayRpc, cooldownMs: 0 })
  check('S2.concurrent-duplicate-returns-same-in-flight-promise', p1 === p2, { samePromise: p1 === p2 })

  const [r1, r2] = await Promise.all([p1, p2])
  check('S2.concurrent-duplicate-runs-gateway-once', gatewayInvocations === 1, { gatewayInvocations })
  check('S2.concurrent-duplicate-persists-one-row', stub.__stats().insertWrites === 1 && stub.__rows().length === 1,
    { stats: stub.__stats(), rows: stub.__rows().length })
  check('S2.concurrent-duplicate-identical-results', JSON.stringify(r1) === JSON.stringify(r2) && r1.changed === 1, { r1, r2 })
}

// S3 — replayed trigger inside the cooldown window is absorbed (lastSyncAtByUserId).
{
  freshWorld()
  const gatewayRpc = newGateway([delivery()])

  const first = await sync.scheduleUserSessionSync({ userId: 'user-1', role: 'user', gatewayRpc })
  const second = await sync.scheduleUserSessionSync({ userId: 'user-1', role: 'user', gatewayRpc })

  check('S3.cooldown-absorbs-duplicate-trigger', first.changed === 1 && second.changed === 0 && second.skipped === true && second.reason === 'cooldown',
    { first, second })
  check('S3.cooldown-duplicate-touches-gateway-once', gatewayRpc.calls.length === 1 && stub.__stats().upsertCalls === 1,
    { gatewayCalls: gatewayRpc.calls.length, stats: stub.__stats() })
}

// S4 — a single delivery that itself repeats the same session row is harmless:
// the second application inside the same scan is a comparison no-op.
{
  freshWorld()
  const gatewayRpc = newGateway([delivery(), delivery()])

  const result = await sync.syncUserSessionsFromGateway({ userId: 'user-1', role: 'user', gatewayRpc })
  const stats = stub.__stats()

  check('S4.repeated-row-in-one-delivery-counted-once', result.scanned === 2 && result.changed === 1 && result.inserted === 1,
    { result })
  check('S4.repeated-row-in-one-delivery-writes-once', stats.upsertCalls === 2 && stats.insertWrites === 1 && stats.updateWrites === 0 &&
    stats.lastResults[1].action === 'unchanged', { stats })
  check('S4.repeated-row-leaves-one-row', stub.__rows().length === 1, { rows: stub.__rows().length })
}

// S5 — duplicate redelivery of a session the user just deleted never resurrects it.
{
  freshWorld()
  const gatewayRpc = newGateway([delivery({ key: 'agent:agent-a:deleted' })])
  const recentlyDeletedSessionKeys = new Set(['agent:agent-a:deleted'])

  const first = await sync.syncUserSessionsFromGateway({ userId: 'user-1', role: 'user', gatewayRpc, recentlyDeletedSessionKeys })
  const second = await sync.syncUserSessionsFromGateway({ userId: 'user-1', role: 'user', gatewayRpc, recentlyDeletedSessionKeys })

  check('S5.deleted-session-redelivery-is-dropped-both-times', first.changed === 0 && second.changed === 0 &&
    stub.__stats().upsertCalls === 0 && stub.__rows().length === 0, { first, second, stats: stub.__stats() })
}

// S6 — normalization is deterministic, so a replayed delivery derives the exact
// same idempotency key and payload (no field drift between deliveries).
{
  freshWorld()
  const payload = { key: SESSION_A, agentId: 'agent-a', lastMessageAt: LAST_ACTIVITY, channel: 'feishu', peer: 'ou_xxx' }
  const a = sync.normalizeGatewaySessionForSync(payload, 'agent-a')
  const b = sync.normalizeGatewaySessionForSync(JSON.parse(JSON.stringify(payload)), 'agent-a')
  check('S6.normalization-deterministic', JSON.stringify(a) === JSON.stringify(b) && a.sessionKey === SESSION_A && a.agentId === 'agent-a',
    { a, b })
  check('S6.unknown-agent-ids-are-unfetchable', sync.extractAgentIdFromSessionKey('no-agent-prefix') === '', {})
}

// S7 — duplicate delivery of a stale (older) snapshot cannot roll the stored
// activity timestamp backwards: last_message_at is a monotonic max.
{
  freshWorld()
  const older = new Date(LAST_ACTIVITY_MS - 60_000).toISOString()
  const newerGateway = newGateway([delivery({ updatedAt: LAST_ACTIVITY })])
  const olderGateway = newGateway([delivery({ updatedAt: older })])

  await sync.syncUserSessionsFromGateway({ userId: 'user-1', role: 'user', gatewayRpc: newerGateway })
  const afterOlderReplay = await sync.syncUserSessionsFromGateway({ userId: 'user-1', role: 'user', gatewayRpc: olderGateway })

  check('S7.stale-duplicate-cannot-regress-activity', afterOlderReplay.changed === 0 &&
    stub.__rows()[0][1].last_message_at === LAST_ACTIVITY_MS, { afterOlderReplay, row: stub.__rows()[0] })
}

// ---------------------------------------------------------------------------
// Report
// ---------------------------------------------------------------------------
for (const r of results) console.log(`${r.ok ? 'PASS' : 'FAIL'} ${r.scenario}`)
const summary = {
  demo: 'duplicate-delivery-is-harmless-for-session-synchronization',
  harness: {
    realSourceExercised: 'server/core/session-sync.js (import specifier rewritten only)',
    persistenceStandIn: '.prale-eval/.harness/user-manager-stub.mjs (transcribed from server/user-manager.js:614-688)',
    statement: 'better-sqlite3 is not installed in this sandbox, so the SQL layer is stood in by an in-memory keyed row store with identical comparison semantics',
  },
  checks: results.length,
  failed: failures.length,
  status: failures.length === 0 ? 'PASS' : 'FAIL',
}
console.log(JSON.stringify(summary, null, 2))
if (failures.length) {
  console.error('FAILURES:\n' + failures.join('\n'))
  process.exit(1)
}
